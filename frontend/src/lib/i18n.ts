/** Every language the UI speaks, named in itself so either can be found from the other. */
export const LANGUAGE_NAMES: Record<Language, string> = { zh: '简体中文', en: 'English' };

/**
 * A language tag as the backend or the browser may spell it: "zh", "zh-CN",
 * "zh_Hans", "en-US"… Anything else is not a language the UI speaks.
 */
export function parseLanguage(value: unknown): Language | null {
  if (typeof value !== 'string') return null;
  const tag = value.trim().toLowerCase().replace(/_/g, '-');
  if (tag === 'zh' || tag.startsWith('zh-')) return 'zh';
  if (tag === 'en' || tag.startsWith('en-')) return 'en';
  return null;
}

/** A missing or unknown language reads as Chinese, the UI's first language. */
export function normalizeLanguage(value: unknown): Language {
  return parseLanguage(value) ?? 'zh';
}

