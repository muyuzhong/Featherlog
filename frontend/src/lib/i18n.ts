const CATALOG: Record<Language, Messages> = { zh, en };

export function messages(language: Language): Messages {
  return CATALOG[language] ?? zh;
}

/** A failed call, kept as what failed rather than as text, so it reads in whatever language is current. */
export interface Notice {
  action: ActionKey;
  /** the backend's error, usually a machine code such as "workbench/not-found"; empty when there was none */
  detail: string;
}

export function noticeText(t: Messages, notice: Notice): string {
  return t.failed(t.actions[notice.action], notice.detail || t.unknownError);
}
